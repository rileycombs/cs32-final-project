# Filtering function
def filter_characters(characters, attribute, value):
    return [c for c in characters if c[attribute] == value]

# Best questions function
def choose_best_question(remaining, used_questions):
    best_question = None
    best_score = -1

    for question in question_bank:

        if question in used_questions:
            continue

        attr, question_text, yes_value = question

        yes_count = 0
        no_count = 0

        for c in remaining:
            if c[attr] == yes_value:
                yes_count += 1
            else:
                no_count += 1

        # better score if split is closer to half and half
        score = min(yes_count, no_count)

        if score > best_score:
            best_score = score
            best_question = question

    return best_question

# Game function
def play_game(characters):
    remaining = characters.copy()
    used_questions = set()

    print("\nThink of a character from The Office!")

    while len(remaining) > 1:

        question = choose_best_question(remaining, used_questions)

        if not question:
            break

        attr, question_text, yes_value = question

        used_questions.add(question)

        answer = input(question_text).strip().lower()

        if answer == "yes":
            remaining = filter_characters(remaining, attr, yes_value)
        elif answer == "no":
            remaining = [c for c in remaining if c[attr] != yes_value]
        else:
            print("Please answer yes or no.")
            continue

        # Show remaining possibilities
        print("\nRemaining characters:")
        for c in remaining:
            print("-", c["name"])
        print()

    # Final result
    if len(remaining) == 1:

        final_character = remaining[0]["name"]

        print("\nI know EXACTLY who this is.")

        # Ask funny final boss question
        if final_character in final_questions:
            input(final_questions[final_character] + " (press enter) ")

        print(f"\nYour character is {final_character}!")

    elif len(remaining) == 0:
        print("No matching character found. Were your answers consistent?")
    else:
        print("I'm not completely sure. Possible characters:")
        for c in remaining:
            print("-", c["name"])

# Replay loop
while True:
    play_game(characters)
    again = input("\nPlay again? (yes/no): ").strip().lower()
    if again != "yes":
        print("Thanks for playing!")
        break
